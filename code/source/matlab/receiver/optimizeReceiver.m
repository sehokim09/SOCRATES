    payload.geomFiles    = string({GEOM.file});
    payload.GRGD_delivered_dB = stored('%.1f', [min(spec.base(1:3)), max(spec.base(1:3))]);   % delivered nadir-to-zenith ratio, SAI bands (min max)
    payload.GRGD_window_dB    = stored('%.1f', [spec.cLo, spec.cHi]);   % Test 2 window common to the SAI transmitters
    payload.altCheck_km  = stored('%g', ALT_CHECK_km);
    payload.passByOrbit  = reshape(stored('%.4f', byOrbit(:)), [nBand nGrp numel(ALT_CHECK_km)]);   % band x group x altitude, worst required port

    %% The rest of the solution
    info = struct();
    info.generated = string(datestr(now, 'yyyy-mm-dd HH:MM')); %#ok<TNOW1,DATST>
    info.summary = sprintf('Worst margin %+.4f on %s (pass %.4f vs requirement %.2f; baseline %.4f on %s); payload %.2f kg, %.1f U.', ...
