function [payload, info] = optimizeReceiver(opts)
% function optimizeReceiver
%
%   Solve the SAI receiver payload: the receiver parameters that deliver
%   usable observations at all four frequencies (137, 255, 370 and 1575 MHz)
%   on the required ports, with the transmitters taken as given, then the
%   lightest design that meets the per-band requirement.
%
%   [payload, info] = optimizeReceiver(opts)
%
%   opts     struct; GEOM is required, the other fields take these defaults
%            (the switches of the ASR SAI design workflow, 2026-10-21):
%     GEOM                 single-receiver geometry sample, struct array with
%                          fields file, label and alt_m (simulation altitude, m);
%                          one receiver per inclination, pooled with equal weight
%     RX_POL               "HVC"   receive polarization: "HV", "LHCP" or "HVC"
%     RMSE_TARGET          NaN     soil-moisture RMSE target; NaN = 0.06 (HV, HVC), 0.10 (LHCP)
%     T_WINDOW_H           12      inter-frequency observation window [hour]
%     RES_MAX_km           25      ground resolution requirement [km]
%     EQUAL_RES            true    tie the dwells so all four bands share one footprint
%     ROUND_IMPL           true    round T_I and the dwell to implementable values
%     T_I_STEP             1e-4    T_I granularity of the SoOp links [s]
%     DWELL_EPOCH          0       output epoch the dwell is a whole number of [s]; 0 = none
%     FIX                  [NaN NaN NaN NaN 1.0 0.8 0.5 500]  pinned values of
%                          [D_gp h T_dwell_VU T_dwell_L NF_VU NF_L L_fe alt_Rx]
%                          (m m s s dB dB dB km); NaN lets the search move it
%     NADIR_FACE           "large" nadir face of the 6U: "large" (20 x 30 cm) or "end" (10 x 20 cm)
%     GP_OPTIONS           []      ground-plane options (label, face_m, D_m, mass_kg),
%                          in preference order; [] = the NADIR_FACE option
%     GNSS_SIG_OPTIONS     {"GPS_L1CA"}  GNSS signal sets to compare (signal names
%                          for gnssEIRPFromICD, or numeric [f_MHz EIRP_dBW] rows)
%     GNSS_EIRP_MODE       "margin"  gnssEIRPFromICD mode
%     GNSS_EIRP_MARGIN_dB  1.0
%     cdfFile              earthdata/reflectivity/reflectivity_CDF_v2.mat
%     verbose              false   print the search log and the design tables
%
%   payload  the solved payload (the struct of solved_payload.m), with every
%            value rounded as solved_payload.m stores it, so the pattern
%            generator and the evaluator see the same numbers
%   info     the rest of the solution: the summary line and generation time,
%            the baseline, the pattern-window specification, the receiver
%            design table and the dwell trade sweep
%
%   Ported from optimize_sai_payload.m of the ASR SAI design (2026-10-21).
%   The search is unchanged: a compass search over the receiver variables
%   per channel count, ground-plane option and GNSS signal set, with the
%   I/P patterns generated by SAIAntennaPattern for every trial. It writes no
%   files and draws no figures.
%
%   See also generateReceiverPatterns, evaluateReceiver, SAIAntennaPattern
%
%   Copyright (C) 2023 Seho Kim
%
%   This file is part of SOCRATES.
%
%   SOCRATES is free software: you can redistribute it and/or modify
%   it under the terms of the GNU General Public License as published by
%   the Free Software Foundation, either version 3 of the License, or
%   (at your option) any later version.
%
%   SOCRATES is distributed in the hope that it will be useful,
%   but WITHOUT ANY WARRANTY; without even the implied warranty of
%   MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.  See the
%   GNU General Public License for more details.
%
%   You should have received a copy of the GNU General Public License
%   along with this program.  If not, see <https://www.gnu.org/licenses/>.
%
%   Version 1.0

    def = struct('RX_POL', "HVC", 'RMSE_TARGET', NaN, 'T_WINDOW_H', 12, ...
        'RES_MAX_km', 25, 'EQUAL_RES', true, 'ROUND_IMPL', true, ...
        'T_I_STEP', 0.1e-3, 'DWELL_EPOCH', 0, 'FIX', [NaN NaN NaN NaN 1.0 0.8 0.5 500], ...
        'NADIR_FACE', "large", 'GP_OPTIONS', [], 'GNSS_SIG_OPTIONS', {{"GPS_L1CA"}}, ...
        'GNSS_EIRP_MODE', "margin", 'GNSS_EIRP_MARGIN_dB', 1.0, ...
        'cdfFile', fullfile('earthdata', 'reflectivity', 'reflectivity_CDF_v2.mat'), ...
        'verbose', false);
    if ~isfield(opts, 'GEOM') || isempty(opts.GEOM)
        error('optimizeReceiver:noGeom', 'opts.GEOM (the single-receiver geometry sample) is required.');
    end
    for f = string(fieldnames(def)).'
        if ~isfield(opts, f), opts.(f) = def.(f); end
    end
    if opts.verbose
        vprintf = @(varargin) fprintf(varargin{:});
    else
        vprintf = @(varargin) [];
    end

    %% Design space and objective
    PASS_FLOOR   = 0.80;   % a band-and-port counts as delivering above this
    GAMMA_REQ    = 0.80;   % per-observation success probability inside Test 2
    T_WINDOW_H   = opts.T_WINDOW_H;
    RES_MAX_km   = opts.RES_MAX_km;
    EQUAL_RES    = opts.EQUAL_RES;

    % Receive polarization: one switch selects the feed network, the
    % retrieval coefficients, the RMSE target and the port requirement.
    %   "HV"    two linear ports X and Y, both required; H&V coefficients, 0.06
    %   "LHCP"  one circular port L, LHCP toward nadir; LHCP coefficients, 0.10
    %   "HVC"   X and Y sampled coherently and combined into L = (X + jY)/sqrt(2);
    %           the H&V products on X and Y are required; H&V coefficients, 0.06
    RX_POL = string(opts.RX_POL);
    if ~any(RX_POL == ["HV" "LHCP" "HVC"]), error('optimizeReceiver:rxpol', 'RX_POL must be "HV", "LHCP" or "HVC".'); end
    switch RX_POL
        case {"HV","HVC"}, RMSE_TARGET = 0.06;     % H&V retrieval either way
        case "LHCP",       RMSE_TARGET = 0.10;
    end
    if ~isnan(opts.RMSE_TARGET), RMSE_TARGET = opts.RMSE_TARGET; end

    % Ports that must deliver, per band
    switch RX_POL
        case "HV"
            PORTS     = ["X","Y"];
            REQ_PORTS = {["X","Y"], ["X","Y"], ["X","Y"], ["X","Y"]};
        case "LHCP"
            PORTS     = "L";
            REQ_PORTS = {"L", "L", "L", "L"};
        case "HVC"
            PORTS     = ["L","X","Y"];              % L synthesized from X and Y
            REQ_PORTS = {["X","Y"], ["X","Y"], ["X","Y"], ["X","Y"]};   % H&V products required at every band; L reported
    end

    % Design variables
    %   1 D_gp       I/P ground-plane side (m), pinned at the ground-plane option
    %   2 h          dipole standoff (m), pinned at the antenna module (H_DEPLOYER)
    %   3 T_dwell_VU I/P-band dwell (s), capped by the resolution requirement
    %   4 T_dwell_L  L-band dwell (s); tied to T_dwell_VU under EQUAL_RES
    %   5 NF_VU      I/P LNA noise figure (dB)
    %   6 NF_L       L-band LNA noise figure (dB)
    %   7 L_fe       front-end loss (dB), ahead of the LNA: attenuates signal and adds noise
    %   8 alt_Rx     receiver altitude (km); only the link geometry scales with it
    VAR_NAME = ["D_gp","h","T_dwell_VU","T_dwell_L","NF_VU","NF_L","L_fe","alt_Rx"];
    VAR_UNIT = ["m","m","s","s","dB","dB","dB","km"];

    % The ground plane is a configuration option, not a continuous variable:
    % each face enters as its area-equivalent square
    FACE_LIB = struct( ...
        'label',   {"end face 10 x 20 cm", "large face 20 x 30 cm"}, ...
        'face_m',  {[0.10 0.20],           [0.20 0.30]}, ...
        'D_m',     {sqrt(0.10*0.20),       sqrt(0.20*0.30)}, ...
        'mass_kg', {0,                     0});
    switch lower(string(opts.NADIR_FACE))
        case "end",   GP_OPTIONS = FACE_LIB(1);
        case "large", GP_OPTIONS = FACE_LIB(2);
        otherwise, error('optimizeReceiver:face', 'NADIR_FACE must be "end" or "large".');
    end
    if ~isempty(opts.GP_OPTIONS), GP_OPTIONS = opts.GP_OPTIONS; end
    nGP        = numel(GP_OPTIONS);
    D_DECK     = GP_OPTIONS(1).D_m;    % option 1 until the search chooses
    H_DEPLOYER = 0.00;      % antenna module is inside the 6U at its nadir end; arms exit at the face plane
    D_SWEEP    = [min([GP_OPTIONS.D_m]), 2.00];
    LB       = [D_SWEEP(1), H_DEPLOYER, 0.20, 0.20, 1.0, 0.5, 0.5, 500];
    UB       = [D_SWEEP(2), 0.30,       5.00, 5.00, 2.0, 2.5, 3.0, 700];
    X0       = [D_DECK,     H_DEPLOYER, 1.00, 1.00, 1.0, 1.5, 2.0, 500];   % today's payload
    iVU = 3;  iL = 4;  iALT = 8;

    % Antenna mass and stowed-volume cost. The design is posed as: meet the
    % pass-fraction requirement, then minimize mass,
    %   objective = min(worst margin, 0) - COST_WEIGHT*(mass/MASS_BUDGET_kg)
    %               + 1e-4*mean(all pass fractions),
    % margin = pass - PASS_REQ_BAND(band) on every required band-and-port;
    % over a budget the design is infeasible and pushed below every feasible one.
    PASS_REQ_BAND   = [0.80 0.80 0.80 0.4];   % per band, on each required port (L-band: L1 only)
    COST_WEIGHT     = 1e-2;   % objective units per (mass / MASS_BUDGET_kg)
    MASS_BUDGET_kg  = 1.5;    % antenna + channel mass allocation on the 6U
    STOW_BUDGET_U   = 2.0;    % stowed-volume allocation, U, on the 6U
    RHO_AREAL_kgm2  = 0.5;    % reflector surface, all-in
    RHO_BOOM_kgm    = 0.15;   % booms and struts, per metre
    M_ELEM_kg       = 0.5;    % trapped 4-arm crossed dipole, deployers, triplexer, hybrids (fixed)
    M_CHAN_kg       = 0.02;   % per correlator channel: a tie-breaker, not hardware
    STOW_ELEM_U     = 0.5;    % elements and deployers, stowed
    STOW_U_PER_M    = 1.5;    % reflector stowed volume per metre of deployed excess
    nVar     = numel(LB);

    % Sky and ground brightness: galactic background
    % T_sky(f) = T_SKY_408_K * (408/f_MHz)^2.75 + 2.7, orbit average over look directions
    T_SKY_408_K = 50;
    SKY_EXP     = 2.75;
    T_EARTH_K   = 260;      % 290 K physical times about 0.9 emissivity, nadir view

    % Pinned variables, applied after the resolution cap on the dwell
    FIX = opts.FIX(:).';
    if numel(FIX) ~= numel(VAR_NAME)
        error('optimizeReceiver:fixLen', 'FIX has %d entries; VAR_NAME has %d (%s).', ...
            numel(FIX), numel(VAR_NAME), strjoin(VAR_NAME, ', '));
    end

    % Channel counts per SoOp band, enumerated: what one spacecraft radiates
    %   ORBCOMM 2 subscriber carriers, UFO 4 (conservative), MUOS 1
    NCH_OPTIONS = {1:2, 1:4, 1};        % GNSS follows the signal set

    % GNSS signal sets, compared like the channel counts; EIRPs derived by
    % gnssEIRPFromICD unless given as numeric [f_MHz EIRP_dBW] rows
    GNSS_SIG_OPTIONS = opts.GNSS_SIG_OPTIONS;
    if ~iscell(GNSS_SIG_OPTIONS), GNSS_SIG_OPTIONS = {GNSS_SIG_OPTIONS}; end
    GNSS_EIRP_MODE = string(opts.GNSS_EIRP_MODE);  GNSS_EIRP_MARGIN_dB = opts.GNSS_EIRP_MARGIN_dB;
    for iOpt = 1:numel(GNSS_SIG_OPTIONS)               % names -> [f_MHz EIRP_dBW] rows
        if isstring(GNSS_SIG_OPTIONS{iOpt}) || ischar(GNSS_SIG_OPTIONS{iOpt}) || iscellstr(GNSS_SIG_OPTIONS{iOpt})
            [eSig, fSig] = gnssEIRPFromICD(string(GNSS_SIG_OPTIONS{iOpt}), 5, GNSS_EIRP_MODE, GNSS_EIRP_MARGIN_dB);
            GNSS_SIG_OPTIONS{iOpt} = [fSig/1e6, eSig];
        else
            warning('optimizeReceiver:gnssEIRPoverride', ...
                'GNSS_SIG option %d is numeric [f EIRP]: EIRP overridden, not derived from the ICD.', iOpt);
        end
    end
    GNSS_SIG = GNSS_SIG_OPTIONS{1};    % option 1 until the search chooses
    T_I_GNSS = 1e-3;   % s; land coherence with data-bit wipeoff, no kappa at L-band
    N_SIG    = size(GNSS_SIG, 1);

    %% Fixed inputs: the transmitters
    c = physconst("lightspeed");  k = physconst("boltzmann");
    R_E = physconst("earthradius");

    BAND    = ["ORBCOMM","UFO","MUOS","GPS"];       % one representative per frequency
    nBand   = numel(BAND);
    isGNSS  = [false false false true];
    freq    = [137e6, 255e6, 370e6, 1575.42e6];
    % MUOS 37 dBW per 5 MHz carrier (Garrison et al. 2024, ASR 73, Table 1)
    EIRP_dB = [12, 27, 37, gnssEIRPFromICD("GPS_L1CA", 5, GNSS_EIRP_MODE, GNSS_EIRP_MARGIN_dB)];   % GPS entry for reference only; the GNSS link uses GNSS_SIG
    BW      = [25e3, 25e3, 5e6, 2.046e6];   % ORBCOMM 25 kHz channel (A80TD0008 Rev G, Table D.1)
    alt_Tx  = [750e3, 35786e3, 35786e3, 20180e3];
    KIND    = ["CROSSDIPOLE","CROSSDIPOLE","CROSSDIPOLE","PATCH"];
    CDFCOL  = [1 2 3 4];
    lambda  = c./freq;
    POLMIS_dB = 3.01;   % direct-path polarization mismatch on a linear port

    % Retrieval coefficients (Kim et al. 2023, Table V, averaged over the two
    % inclinations); eta_avg is fixed by the RMSE target
    switch RX_POL
        case {"HV","HVC"}
            a_SM_eta = (0.4369 + 0.4232)/2;
            a_SM_T   = (2.363e-4 + 3.204e-4)/2;
            b_SM     = (0.0378 + 0.0370)/2;
        case "LHCP"
            a_SM_eta = (0.6222 + 0.6385)/2;
            a_SM_T   = (2.542e-4 + 2.277e-4)/2;
            b_SM     = (0.0844 + 0.0789)/2;
    end
    if RMSE_TARGET <= b_SM + a_SM_T*T_WINDOW_H
        error('optimizeReceiver:infeasibleRMSE', ...
              'RMSE target %.4f is at or below the retrieval floor %.4f.', ...
              RMSE_TARGET, b_SM + a_SM_T*T_WINDOW_H);
    end
    eta_avg = sqrt((RMSE_TARGET-b_SM)^2 - (a_SM_T*T_WINDOW_H)^2)/a_SM_eta;

    %% Precompute
    %   Everything that does not depend on the design vector is computed once;
    %   per observation the grid index of each arrival direction is stored, and
    %   the objective reads the freshly generated pattern at those indices.
    %   Altitude is handled by ratio scaling of the simulated ranges, so
    %   altitude results describe per-observation link quality at fixed
    %   sampling, not coverage.
    vprintf('\n===== OPTIMIZE RECEIVER  (RX_POL = %s, RMSE target %.2f) =====\n', RX_POL, RMSE_TARGET);
    vprintf('  GNSS signals tracked: %d  (', N_SIG);
    vprintf('%.2f MHz ', GNSS_SIG(:,1)); vprintf(')\n');
    vprintf('  precomputing geometry and arrival-direction indices ...\n');

    GEOM = opts.GEOM;
    keep = arrayfun(@(g) isfile(g.file), GEOM);
    for ig = find(~keep)
        warning('optimizeReceiver:geomMissing', 'geometry file %s not found; skipped.', GEOM(ig).file);
    end
    GEOM = GEOM(keep);
    if isempty(GEOM), error('optimizeReceiver:noGeom', 'No geometry sample file found.'); end
    nGrp    = numel(GEOM);
    GRP_LBL = string({GEOM.label});
    ALT_REF = 500e3;                        % reference altitude of the scaling; per-file altitude is in P.altRef
    STRIDE  = [10, 10, 10, 80];
    RES_DEG = 1.0;                          % pattern grid; must match SAIAntennaPattern

    Scdf = load(opts.cdfFile);

    PRE = struct();
    for ib = 1:nBand
        nm = BAND(ib);
        P = struct('rangeTR',[], 'rangeTS',[], 'rangeSR',[], 'theta',[], 'iR',[], 'iD',[], 'thR',[], 'thD',[], 'grp',[], 'altRef',[]);
        for ig = 1:nGrp
            raw = readSpDataNc(GEOM(ig).file, ["ORBCOMM","UFO","MUOS","GPS"]);
            T = raw.(nm);
            if nm == "MUOS", T = T(logical(raw.flagSpotbeam),:); end
            sel = 1:STRIDE(ib):height(T);
            aRef = GEOM(ig).alt_m;
            theta = asin(min(1, max(-1, (R_E+aRef)*sin(T.lookAngElR(sel))/R_E)));
            theta(~isfinite(theta)) = pi/2;
            P.rangeTR = [P.rangeTR; T.rangeTR(sel)];  P.rangeTS = [P.rangeTS; T.rangeTS(sel)];
            P.rangeSR = [P.rangeSR; T.rangeSR(sel)];  P.theta   = [P.theta; theta];
            % linear grid indices of the two arrival directions, nadir frame;
            % the direct arrival is read at its stored angle (back hemisphere)
            P.iR = [P.iR; localGridIndex(T.lookAngElR(sel), T.lookAngAzR(sel), RES_DEG)];
            P.iD = [P.iD; localGridIndex(T.lookAngElD(sel), T.lookAngAzD(sel), RES_DEG)];
            P.thR = [P.thR; T.lookAngElR(sel)];  P.thD = [P.thD; T.lookAngElD(sel)];   % nadir-frame arrival angles, rad
            P.grp    = [P.grp;    ig*ones(numel(sel),1)];
            P.altRef = [P.altRef; aRef*ones(numel(sel),1)];
        end
        P.n = numel(P.grp);
        P.nGrp = nGrp;
        for port = ["X","Y","L"]
            Xc = Scdf.X.(char(port))(:,CDFCOL(ib));  Fc = Scdf.F.(char(port))(:,CDFCOL(ib));
            ok = isfinite(Xc) & isfinite(Fc);
            [Xu, iu] = unique(Xc(ok), 'last');  Fu = Fc(ok);  Fu = Fu(iu);
            P.cdfX.(port) = Xu;  P.cdfF.(port) = Fu;
            [Fq, iq] = unique(Fu, 'first');
            P.Ginv.(port) = interp1(Fq, Xu(iq), 1-GAMMA_REQ, 'linear', 'extrap');
        end
        PRE.(nm) = P;
        vprintf('    %-8s %7d observations in %d geometry group(s)\n', nm, P.n, nGrp);
    end
    vprintf('  geometry groups (equal weight): %s\n', strjoin(GRP_LBL, ' | '));

    % The L-band patch is fixed, so its pattern is generated once here
    PATCH_L = SAIAntennaPattern('PATCH', freq(4)/1e6, D_DECK, 0, RES_DEG);
    vprintf('    L-band patch: %.2f dBi, F/B %.1f dB, back fraction %.3f (fixed)\n', ...
            PATCH_L.G_realized_dBi, PATCH_L.FB_cone_dB, PATCH_L.backFrac);

    % Resolution cap on the dwell. Footprint = first Fresnel zone (along-track
    % diameter, median over the sample) + along-track smear v_gnd*T_dwell.
    v_gnd = sqrt(3.986004418e14/(R_E+ALT_REF))*R_E/(R_E+ALT_REF);
    FZ_m = zeros(1, nBand);
    for ib = 1:nBand
        P = PRE.(BAND(ib));
        Reff = P.rangeSR.*P.rangeTS./(P.rangeSR + P.rangeTS);
        FZ_m(ib) = median(2*sqrt(lambda(ib)*Reff)./max(cos(P.theta), 0.2));
    end
    FZ_VU = max(FZ_m(1:3));  FZ_L = FZ_m(4);
    capVU = (RES_MAX_km*1e3 - FZ_VU)/v_gnd;
    capL  = (RES_MAX_km*1e3 - FZ_L )/v_gnd;
    UB(iVU) = min(UB(iVU), capVU);
    UB(iL)  = min(UB(iL),  capL);
    vprintf('\n  resolution requirement %.1f km (CYGNSS class): Fresnel diameter [%s] m\n', RES_MAX_km, sprintf('%.0f ', FZ_m));
    vprintf('  caps T_dwell_VU at %.3f s and T_dwell_L at %.3f s (v_gnd %.2f km/s)\n', UB(iVU), UB(iL), v_gnd/1e3);
    % Implementation granularity, applied to the cap so the search (and the
    % channel counts that depend on the dwell) runs on implementable dwells
    T_I_STEP    = opts.T_I_STEP;
    DWELL_EPOCH = opts.DWELL_EPOCH;
    ROUND_IMPL  = opts.ROUND_IMPL;
    if ROUND_IMPL && DWELL_EPOCH > 0
        UB(iVU) = max(DWELL_EPOCH, floor(UB(iVU)/DWELL_EPOCH + 1e-9)*DWELL_EPOCH);
        UB(iL)  = max(DWELL_EPOCH, floor(UB(iL) /DWELL_EPOCH + 1e-9)*DWELL_EPOCH);
        vprintf('  implementable caps (whole %.2g s epochs): T_dwell_VU <= %.2f s, T_dwell_L <= %.2f s\n', DWELL_EPOCH, UB(iVU), UB(iL));
        if (RES_MAX_km*1e3 - FZ_VU)/v_gnd - UB(iVU) > 0.5*DWELL_EPOCH
            vprintf('  NOTE: the epoch costs %.2f s of admissible I/P dwell (%.1f dB on the reflected leg); a finer DWELL_EPOCH recovers it.\n', ...
                    (RES_MAX_km*1e3 - FZ_VU)/v_gnd - UB(iVU), 10*log10(((RES_MAX_km*1e3 - FZ_VU)/v_gnd)/UB(iVU)));
        end
    end
    DWELL_OFFSET = (FZ_VU - FZ_L)/v_gnd;      % T_dwell_L - T_dwell_VU at equal footprint
    % Equal footprint at I/P-band too: x(iVU) is the dwell of the band with
    % the largest Fresnel zone; each other I/P band dwells longer by its deficit
    if EQUAL_RES, OFF_IP = (FZ_VU - FZ_m(1:3))/v_gnd; else, OFF_IP = zeros(1,3); end
    vprintf('  equal footprint: I/P dwell offsets [%s] s, L-band +%.3f s\n', sprintf('%.3f ', OFF_IP), DWELL_OFFSET);
    if EQUAL_RES
        vprintf('  EQUAL_RES: T_dwell_L = T_dwell_VU + %.3f s so all four bands share one footprint\n', DWELL_OFFSET);
        if ~isnan(FIX(iL)), warning('optimizeReceiver:tiedDwell', 'T_dwell_L is tied under EQUAL_RES; its FIX entry is ignored.'); end
        LB(iL) = 0;  UB(iL) = 0;  X0(iL) = 0;  FIX(iL) = 0;    % placeholder, not searched
    end

    %% Objective
    %   The worst band-and-port pass fraction (maximin): a multi-frequency
    %   retrieval needs every band, so a sum would prefer the wrong design.
    CONST = struct('POLMIS',POLMIS_dB, 'T408',T_SKY_408_K, 'EXPO',SKY_EXP, ...
        'TEARTH',T_EARTH_K, 'eta_avg',eta_avg, 'gammaReq',GAMMA_REQ, 'R_E',R_E, ...
        'c',c, 'kB',k, 'ALT_REF',ALT_REF, 'reqPorts',{REQ_PORTS}, ...
        'GNSS_SIG',GNSS_SIG, 'T_I_GNSS',T_I_GNSS, 'RES_DEG',RES_DEG, 'PATCH_L',PATCH_L, ...
        'RX_POL',RX_POL, 'PORTS',PORTS, 'EQUAL_RES',EQUAL_RES, 'DWELL_OFFSET',DWELL_OFFSET, 'OFF_IP',OFF_IP, ...
        'PASS_REQ_BAND',PASS_REQ_BAND, 'COST_WEIGHT',COST_WEIGHT, 'MASS_BUDGET_kg',MASS_BUDGET_kg, ...
        'STOW_BUDGET_U',STOW_BUDGET_U, 'RHO_AREAL',RHO_AREAL_kgm2, 'RHO_BOOM',RHO_BOOM_kgm, ...
        'M_ELEM',M_ELEM_kg, 'M_CHAN',M_CHAN_kg, 'STOW_ELEM_U',STOW_ELEM_U, ...
        'STOW_U_PER_M',STOW_U_PER_M, 'D_DECK',D_DECK, 'H_DEPLOYER',H_DEPLOYER, 'GP_MASS',GP_OPTIONS(1).mass_kg, ...
        'DWELL_EPOCH',localIf(ROUND_IMPL, DWELL_EPOCH, 0));
    % the braces around REQ_PORTS: struct() given a bare cell array builds a
    % struct array with one element per cell
    % Pattern cache shared by every objective call of this run: the I/P
    % patterns are regenerated only when (D_gp, h, alt_Rx) changes
    CONST.CACHE = containers.Map();

    objective = @(x, nch) localMaximin(x, nch, PRE, BAND, isGNSS, freq, lambda, ...
        EIRP_dB, BW, alt_Tx, KIND, CONST);

    nch0 = [2 4 1 N_SIG];
    [~, d0, i0] = objective(X0, nch0);
    vprintf('\n  baseline payload (bare deck): worst margin %+.3f on %s (pass %.3f vs requirement %.2f);   payload %.2f kg, %.1f U\n', ...
            i0.marginWorst, i0.bandWorst, i0.passAtWorst, i0.reqAtWorst, i0.cost.mass_kg, i0.cost.stow_U);
    localPrintDetail(d0, BAND, vprintf);
    localPrintAntenna(i0, BAND, freq, 'BASELINE', RX_POL, vprintf);

    %% Maximin search
    %   Compass (coordinate pattern) search with a shrinking step, once per
    %   combination of ground-plane option, GNSS signal set and SoOp channel
    %   counts. D_gp and h are pinned inside the search: the ground plane comes
    %   from GP_OPTIONS, the standoff is the module (H_DEPLOYER).
    if ~isnan(FIX(1)) || ~isnan(FIX(2))
        vprintf('  NOTE: FIX entries for D_gp / h are ignored; the ground plane comes from GP_OPTIONS and h = H_DEPLOYER.\n');
    end
    FIX(1) = NaN;  FIX(2) = H_DEPLOYER;
    isFixed = ~isnan(FIX);  isFixed(1) = true;
    for iv = find(isFixed)
        if iv ~= 1 && (FIX(iv) < LB(iv) || FIX(iv) > UB(iv))
            warning('optimizeReceiver:fixOutsideBounds', ...
                '%s is pinned at %g, outside its bound [%g, %g]. The pin wins.', ...
                VAR_NAME(iv), FIX(iv), LB(iv), UB(iv));
        end
    end
    iv2 = find(isFixed);  iv2(iv2 == 1) = [];
    LB(iv2) = FIX(iv2);  UB(iv2) = FIX(iv2);  X0(iv2) = FIX(iv2);
    vprintf('  pinned:  D_gp = ground plane option (see below)');
    for iv = iv2
        if EQUAL_RES && iv == iL, continue; end
        vprintf('  %s = %g %s', VAR_NAME(iv), FIX(iv), VAR_UNIT(iv));
    end
    vprintf('\n');
    if any(LB(2:end) > UB(2:end))
        iBad = 1 + find(LB(2:end) > UB(2:end));
        error('optimizeReceiver:crossedBounds', ...
            '%s has LB = %g above UB = %g. If you meant to pin it, use FIX.', ...
            VAR_NAME(iBad(1)), LB(iBad(1)), UB(iBad(1)));
    end
    if sum(~isFixed) == 0
        error('optimizeReceiver:nothingFree', 'Every variable is pinned.');
    end

    vprintf('\n  searching (%d ground-plane option(s) x %d x %d channel counts) ...\n', nGP, numel(NCH_OPTIONS{1}), numel(NCH_OPTIONS{2}));
    gpRes = struct('F', num2cell(-inf(1,nGP)), 'X', [], 'N', [], 'S', 1, 'margin', num2cell(-inf(1,nGP)), 'mass', 0);
    searchLog = struct('gp', {}, 'nSig', {}, 'nch', {}, 'objective', {}, 'passBand', {}, 'marginWorst', {}, 'mass_kg', {});
    for ig = 1:nGP
        opt = GP_OPTIONS(ig);
        CONST.D_DECK  = opt.D_m;
        CONST.GP_MASS = opt.mass_kg;
        CONST.PATCH_L = SAIAntennaPattern('PATCH', freq(4)/1e6, opt.D_m, 0, RES_DEG);   % L-band patch on this plane
        LBg = LB;  UBg = UB;  X0g = X0;
        LBg(1) = opt.D_m;  UBg(1) = opt.D_m;  X0g(1) = opt.D_m;
        vprintf('  ground plane %d/%d: %s  (D = %.3f m, %.3f / %.3f / %.3f lambda)\n', ig, nGP, opt.label, opt.D_m, opt.D_m./lambda(1:3));
        bF = -Inf;  bX = X0g;  bN = nch0;  bS = 1;
        for isig = 1:numel(GNSS_SIG_OPTIONS)
            CONST.GNSS_SIG = GNSS_SIG_OPTIONS{isig};  nS = size(CONST.GNSS_SIG, 1);
            objective = @(x, nch) localMaximin(x, nch, PRE, BAND, isGNSS, freq, lambda, ...
                EIRP_dB, BW, alt_Tx, KIND, CONST);
            for n1 = NCH_OPTIONS{1}
                for n2 = NCH_OPTIONS{2}
                    nch = [n1 n2 NCH_OPTIONS{3}(1) nS];     % GNSS count = signals tracked
                    [xo, fo] = localCompassSearch(@(x) objective(x, nch), X0g, LBg, UBg);
                    [~, ~, iC] = objective(xo, nch);
                    vprintf('    GNSS %d signal(s), ORBCOMM x%d, UFO x%d: objective %+.4f   pass per band [%s]  worst margin %+.3f on %s  dwell %.2f s  %.2f kg\n', ...
                            nS, n1, n2, fo, sprintf('%.3f ', iC.passBand), iC.marginWorst, iC.bandWorst, xo(iVU), iC.cost.mass_kg);
                    searchLog(end+1) = struct('gp', ig, 'nSig', nS, 'nch', nch, 'objective', fo, ...
                        'passBand', iC.passBand, 'marginWorst', iC.marginWorst, 'mass_kg', iC.cost.mass_kg); %#ok<AGROW>
                    if fo > bF, bF = fo; bX = xo; bN = nch; bS = isig; end
                end
            end
        end
        CONST.GNSS_SIG = GNSS_SIG_OPTIONS{bS};
        objective = @(x, nch) localMaximin(x, nch, PRE, BAND, isGNSS, freq, lambda, ...
            EIRP_dB, BW, alt_Tx, KIND, CONST);
        [~, ~, iG] = objective(bX, bN);
        gpRes(ig).F = bF;  gpRes(ig).X = bX;  gpRes(ig).N = bN;  gpRes(ig).S = bS;
        gpRes(ig).margin = iG.marginWorst;  gpRes(ig).mass = iG.cost.mass_kg;
        vprintf('    -> worst margin %+.3f on %s, %.2f kg\n', iG.marginWorst, iG.bandWorst, iG.cost.mass_kg);
    end
    % choose the first option (preference order) that meets the requirement,
    % else the best worst-margin
    igMeet = find([gpRes.margin] >= -1e-9, 1, 'first');
    if isempty(igMeet), [~, igSel] = max([gpRes.margin]); else, igSel = igMeet; end
    GP_SEL     = GP_OPTIONS(igSel);
    BUS_FACE_m = GP_SEL.face_m;   D_DECK = GP_SEL.D_m;
    CONST.D_DECK = D_DECK;  CONST.GP_MASS = GP_SEL.mass_kg;
    CONST.PATCH_L = SAIAntennaPattern('PATCH', freq(4)/1e6, D_DECK, 0, RES_DEG);
    % this objective keeps the GNSS signal set of the last option searched
    % (the original order; the rounding step below rebuilds it with the chosen set)
    objective = @(x, nch) localMaximin(x, nch, PRE, BAND, isGNSS, freq, lambda, ...
        EIRP_dB, BW, alt_Tx, KIND, CONST);
    bestN = gpRes(igSel).N;  bestX = gpRes(igSel).X;
    GNSS_SIG = GNSS_SIG_OPTIONS{gpRes(igSel).S};  N_SIG = size(GNSS_SIG, 1);  CONST.GNSS_SIG = GNSS_SIG;
    vprintf('  GNSS signal set chosen: %d signal(s) (%s MHz)\n', N_SIG, strtrim(sprintf('%.2f ', GNSS_SIG(:,1))));
    LB(1) = D_DECK;  UB(1) = D_DECK;  X0(1) = D_DECK;   % pinned at the chosen plane from here on
    FIX(1) = D_DECK;
    vprintf('  ground plane chosen: %s%s\n', GP_SEL.label, localIf(isempty(igMeet), '  (no option meets the requirement; best worst-margin)', '  (first option in preference order that meets the requirement)'));

    if EQUAL_RES, bestX(iL) = bestX(iVU) + DWELL_OFFSET; X0(iL) = X0(iVU) + DWELL_OFFSET; end
    [fBest, dBest, iBest] = objective(bestX, bestN);
    vprintf('\n===== REQUIREMENT-THEN-MASS DESIGN =====\n');
    vprintf('  requirement per band on the required ports [%s]: [%s]\n', strjoin(BAND, ' '), sprintf('%.2f ', PASS_REQ_BAND));
    vprintf('  pass per band (min over required ports):      [%s]   margin [%s]\n', sprintf('%.3f ', iBest.passBand), sprintf('%+.3f ', iBest.margin));
    vprintf('  worst margin %+.3f on %s (pass %.3f vs requirement %.2f; baseline %.3f on %s)\n', ...
            iBest.marginWorst, iBest.bandWorst, iBest.passAtWorst, iBest.reqAtWorst, i0.passAtWorst, i0.bandWorst);
    vprintf('  payload mass: %.2f kg of %.1f kg   (reflector %.2f, booms %.2f, standoff %.2f, elements %.2f, channels %.2f);   stowed %.1f of %.1f U\n', ...
            iBest.cost.mass_kg, MASS_BUDGET_kg, iBest.cost.surface_kg, iBest.cost.booms_kg, ...
            iBest.cost.standoff_kg, iBest.cost.elements_kg, iBest.cost.channels_kg, iBest.cost.stow_U, STOW_BUDGET_U);
    if iBest.marginWorst < -1e-6
        vprintf('  NOTE: the requirement is NOT met inside the budgets; this is the best worst-margin the budget allows.\n');
    end
    vprintf('  channels: ORBCOMM x%d, UFO x%d, MUOS x%d, GNSS %d signal(s)\n', bestN);
    vprintf('%-10s %10s %10s %10s %8s\n','variable','baseline','optimum','bound lo','bound hi');
    for iv = 1:nVar
        atB = '';
        if ~isFixed(iv) && (abs(bestX(iv)-LB(iv)) < 1e-6 || abs(bestX(iv)-UB(iv)) < 1e-6)
            atB = '  <- at bound';
        end
        vprintf('%-10s %10.3f %10.3f %10.3f %8.3f   %s%s\n', VAR_NAME(iv), X0(iv), ...
                bestX(iv), LB(iv), UB(iv), VAR_UNIT(iv), atB);
    end
    localPrintDetail(dBest, BAND, vprintf);
    localPrintAntenna(iBest, BAND, freq, 'OPTIMUM', RX_POL, vprintf);
    % Implementation rounding of the tied L-band dwell (the search already ran
    % with its dwell cap at the largest implementable value; each I/P band is
    % rounded after its offset)
    if ROUND_IMPL
        dwOpt = bestX([iVU iL]);
        if DWELL_EPOCH > 0, bestX(iL) = max(DWELL_EPOCH, floor(bestX(iL)/DWELL_EPOCH + 1e-9)*DWELL_EPOCH); end
        CONST.EQUAL_RES = false;                       % dwells are now explicit
        objective = @(x, nch) localMaximin(x, nch, PRE, BAND, isGNSS, freq, lambda, ...
            EIRP_dB, BW, alt_Tx, KIND, CONST);
        mOpt = iBest.marginWorst;
        [fBest, dBest, iBest] = objective(bestX, bestN);
        vprintf('\n  implementation rounding: dwell [%.2f %.2f] -> [%.2f %.2f] s (whole %.2g s epochs);  worst margin %+.3f -> %+.3f\n', ...
                dwOpt, bestX([iVU iL]), DWELL_EPOCH, mOpt, iBest.marginWorst);
    end
    TdIPbest = bestX(iVU) + OFF_IP;
    if ROUND_IMPL && DWELL_EPOCH > 0, TdIPbest = max(DWELL_EPOCH, floor(TdIPbest/DWELL_EPOCH + 1e-9)*DWELL_EPOCH); end
    Tdw7best = [TdIPbest bestX(iL)*[1 1 1 1]];
    RES7_km  = ([FZ_m(1:3) FZ_m(4)*[1 1 1 1]] + v_gnd*Tdw7best)/1e3;
    vprintf('\n  footprint per band (Fresnel + smear): [%s] km  (requirement %.1f km)\n', sprintf('%.1f ', RES7_km(1:4)), RES_MAX_km);

    %% Receiver design table: the solved values of the receiver parameters
    reqTab = struct('name', {}, 'sense', {}, 'solved', {}, 'req', {}, 'unit', {}, 'band', {});
    for iv = [find(VAR_NAME == "NF_VU"), find(VAR_NAME == "NF_L"), find(VAR_NAME == "L_fe")]
        reqTab(end+1) = struct('name', VAR_NAME(iv), 'sense', "<=", 'solved', bestX(iv), 'req', bestX(iv), 'unit', VAR_UNIT(iv), 'band', "--"); %#ok<AGROW>
    end
    for iv = [iVU iL]
        reqTab(end+1) = struct('name', VAR_NAME(iv), 'sense', ">=", 'solved', bestX(iv), 'req', bestX(iv), 'unit', VAR_UNIT(iv), 'band', "--"); %#ok<AGROW>
    end
    chanLbl = ["N_ch ORBCOMM", "N_ch UFO"];
    for ic = 1:2
        reqTab(end+1) = struct('name', chanLbl(ic), 'sense', ">=", 'solved', bestN(ic), 'req', bestN(ic), 'unit', "", 'band', "--"); %#ok<AGROW>
    end
    reqTab(end+1) = struct('name', "GNSS signals", 'sense', ">=", 'solved', N_SIG, 'req', N_SIG, 'unit', "", 'band', "--");

    vprintf('\n===== RECEIVER DESIGN =====\n');
    vprintf('  %-14s %8s %6s\n', 'parameter', 'solved', 'unit');
    for ir = 1:numel(reqTab)
        vprintf('  %-14s %8.3g %6s\n', reqTab(ir).name, reqTab(ir).solved, reqTab(ir).unit);
    end

    % One payload for all orbits: the design is held fixed through the
    % constellation tradespace, so report it per geometry group and at the
    % altitude extremes (worst required port per band)
    ALT_CHECK_km = unique([bestX(iALT), 500, 700]);
    byOrbit = nan(nBand, nGrp, numel(ALT_CHECK_km));
    for ia = 1:numel(ALT_CHECK_km)
        xa = bestX;  xa(iALT) = ALT_CHECK_km(ia);
        [~, dA] = objective(xa, bestN);
        for ib = 1:nBand
            req = REQ_PORTS{ib};  w = inf(1, nGrp);
            for port = req, w = min(w, dA.(BAND(ib)).byGroup.(port)); end
            byOrbit(ib, :, ia) = w;
        end
    end
    vprintf('\n===== FIXED PAYLOAD ACROSS ORBITS (worst required port) =====\n');
    for ia = 1:numel(ALT_CHECK_km)
        vprintf('  altitude %g km%s\n', ALT_CHECK_km(ia), ...
            localIf(abs(ALT_CHECK_km(ia)*1e3 - ALT_REF) > 1, ' (link geometry scaled)', ''));
        vprintf('  %-9s', 'band'); vprintf(' %14s', GRP_LBL); vprintf('\n');
        for ib = 1:nBand
            vprintf('  %-9s', BAND(ib)); vprintf(' %14.3f', byOrbit(ib, :, ia)); vprintf('\n');
        end
    end
    reqB = reshape(PASS_REQ_BAND(:), [], 1);
    if all(byOrbit >= reqB, 'all')
        vprintf('  every band on every orbit meets its requirement [%s]: the payload is constellation-independent.\n', sprintf('%.2f ', PASS_REQ_BAND));
    else
        vprintf('  entries below their band requirement [%s] mark payload-limited candidates.\n', sprintf('%.2f ', PASS_REQ_BAND));
    end
    if N_SIG == 1 && RX_POL == "HV" && any([dBest.GPS.X] < PASS_REQ_BAND(4))
        vprintf(['\n  NOTE: L-band port X is below the floor. With L1 alone this is\n' ...
                 '  expected and no antenna fixes it; add L2C and L5 to GNSS_SIG.\n']);
    end

    %% Dwell trade
    %   Pass fraction per band (min over the required ports) against the I/P
    %   dwell at the solved receiver and channel counts, with the dwells
    %   entering continuously; the L-band dwell keeps the solved offset.
    nSw = 36;  Tsw = linspace(0.2, 1.25*capVU, nSw);
    passT = nan(nSw, nBand);
    CONSTsw = CONST;  CONSTsw.DWELL_EPOCH = 0;
    objSw = @(x, nch) localMaximin(x, nch, PRE, BAND, isGNSS, freq, lambda, EIRP_dB, BW, alt_Tx, KIND, CONSTsw);
    offL = bestX(iL) - bestX(iVU);
    for is = 1:nSw
        xt = bestX;  xt(iVU) = Tsw(is);  xt(iL) = Tsw(is) + offL;
        [~, dT] = objSw(xt, bestN);
        for ib = 1:nBand
            v = Inf;  for p = REQ_PORTS{ib}, v = min(v, dT.(BAND(ib)).(p)); end
            passT(is, ib) = v;
        end
    end
    fpT = (FZ_VU + v_gnd*Tsw)/1e3;                     % design footprint, km

    %% Antenna pattern specification
    %   The admissible window of nadir-to-zenith gain ratio G_R/G_D for each
    %   SAI transmitter, by shifting the zenith response of the solved pattern
    %   and re-evaluating both tests; the window is where both pass fractions
    %   stay above PASS_FLOOR.
    ASYM_SWEEP_dB = -10:0.25:30;                       % shift of the zenith response, dB
    specPort = PORTS(1);                                % L for LHCP/HVC, X for HV
    spec = localAntennaWindow(bestX, bestN, iBest, PRE, BAND, isGNSS, lambda, ...
                              EIRP_dB, BW, alt_Tx, CONST, ASYM_SWEEP_dB, specPort, PASS_FLOOR);
    vprintf('\n===== ANTENNA PATTERN SPECIFICATION (port %s, both tests >= %.2f) =====\n', specPort, PASS_FLOOR);
    vprintf('%-9s %10s %18s %9s %10s %20s\n', 'band', 'delivered', 'G_R/G_D window', 'optimum', 'G_D floor', 'upper edge set by');
    for ib = 1:3
        vprintf('%-9s %8.1f dB %8.1f to %-6.1f %7.1f dB %7.1f dBi %20s\n', BAND(ib), spec.base(ib), ...
                spec.lo(ib), spec.hi(ib), spec.opt(ib), spec.GDfloor(ib), spec.limit(ib));
    end
    vprintf('  common: %.1f to %.1f dB (nominal %.1f), G_D >= %.1f dBi; delivered %.1f to %.1f dB\n', ...
            spec.cLo, spec.cHi, (spec.cLo+spec.cHi)/2, spec.cGD, min(spec.base(1:3)), max(spec.base(1:3)));

    %% Per-transmitter values
    TX7  = ["ORBCOMM","UFO","MUOS","GPS","Galileo","GLONASS","Beidou"];
    map7 = [1 2 3 4 4 4 4];
    T_integ7 = nan(1,7);  G_ant7 = nan(1,7);  Tnoise7 = nan(1,7);
    FB7 = nan(1,7);  back7 = nan(1,7);  NCH7 = ones(1,7);
    for it = 1:7
        ib = map7(it);  A = iBest.(BAND(ib));
        if any(RX_POL == ["HV","HVC"])
            G_ant7(it) = A.G_realized_dBi;    FB7(it) = A.FB_cone_dB;  back7(it) = A.backFrac;
        else
            G_ant7(it) = A.G_realized_cp_dBi;  FB7(it) = A.FBcp_dB;     back7(it) = A.backFrac_cp;
        end
        Tnoise7(it) = A.Tsys;   NCH7(it) = bestN(ib);
        if isGNSS(ib)
            T_integ7(it) = T_I_GNSS;
        else
            P = PRE.(BAND(ib));
            [sTR, sTS, sSR] = localAltScale(P.theta, alt_Tx(ib), P.altRef, bestX(iALT)*1e3, R_E);
            tau = (P.rangeTS.*sTS + P.rangeSR.*sSR - P.rangeTR.*sTR)/c;
            T_integ7(it) = max(min(tau), 1e-5);
        end
    end
    % Implementation rounding, down so no rounded value violates a
    % constraint: T_I to a multiple of T_I_STEP below min tau_RD (GNSS keeps
    % its code-epoch value), N_incoh the integer that fills the dwell
    T_integ7_opt = T_integ7;
    if ROUND_IMPL
        for it = 1:7
            if ~isGNSS(map7(it))
                T_integ7(it) = max(T_I_STEP, floor(T_integ7(it)/T_I_STEP)*T_I_STEP);
            end
        end
        vprintf('  implementation rounding: T_I [%s] -> [%s] ms (multiples of %.1f ms, below min tau_RD)\n', ...
                sprintf('%.3f ', T_integ7_opt(1:4)*1e3), sprintf('%.3f ', T_integ7(1:4)*1e3), T_I_STEP*1e3);
    end
    N_incoh7 = max(1, floor(Tdw7best ./ T_integ7 + 1e-9));

    %% Solved payload, rounded as solved_payload.m stores it
    % 10th-90th percentile nadir angles of the reflected and direct
    % arrivals, pooled over the three SAI bands of the geometry sample
    arrR = [];  arrD = [];
    for ib = 1:3, arrR = [arrR; PRE.(BAND(ib)).thR(:)]; arrD = [arrD; PRE.(BAND(ib)).thD(:)]; end %#ok<AGROW>
    arrR = sort(arrR(isfinite(arrR))*180/pi);  arrD = sort(arrD(isfinite(arrD))*180/pi);
    pctIx = @(v, p) v(min(numel(v), max(1, round(p/100*numel(v)))));

    payload = struct();
    payload.order        = TX7;
    payload.RX_POL       = RX_POL;                     % feed network the design was optimized for
    payload.gp_option    = string(GP_SEL.label);       % ground plane chosen (preference order, first that meets the requirement)
    payload.bus_face_m   = stored('%.3g', BUS_FACE_m); % nadir face of the 6U
    payload.D_deck_m     = stored('%.6g', D_DECK);     % area-equivalent bare face (ground plane of the L-band patch)
    payload.D_gp_m       = stored('%.6g', bestX(1));   % I/P reflector side (= D_deck_m: no reflector)
    payload.h_m          = stored('%.6g', bestX(2));   % dipole standoff
    payload.T_dwell_s    = stored('%.6g', Tdw7best);   % per transmitter, seconds
    payload.arrR_deg     = stored('%.1f', [pctIx(arrR,10), pctIx(arrR,90)]);   % reflected-arrival nadir angle, p10 p90 (SAI bands)
    payload.arrD_deg     = stored('%.1f', [pctIx(arrD,10), pctIx(arrD,90)]);   % direct-arrival nadir angle, p10 p90 (SAI bands)
    payload.res_km       = stored('%.3g', RES7_km);    % footprint: Fresnel diameter + along-track smear
    payload.RES_MAX_km   = stored('%g', RES_MAX_km);   % resolution requirement
    payload.EQUAL_RES    = double(EQUAL_RES);
    payload.ROUND_IMPL   = double(ROUND_IMPL);         % 1 = T_I and dwell rounded to implementable values
    payload.T_I_STEP_s   = stored('%g', T_I_STEP);
    payload.DWELL_EPOCH_s = stored('%g', DWELL_EPOCH);
    payload.NF_VU_dB     = stored('%.6g', bestX(5));   % I/P LNA noise figure
    payload.NF_L_dB      = stored('%.6g', bestX(6));   % L-band LNA noise figure
    payload.L_misc_dB    = stored('%.6g', bestX(7));   % dB, not linear; front-end loss
    payload.alt_Rx_m     = stored('%.6g', bestX(iALT)*1e3);   % metres
    payload.GNSS_SIG     = [stored('%.2f', GNSS_SIG(:,1)).', stored('%.3f', GNSS_SIG(:,2)).'];  % [f_MHz EIRP_dBW]
    payload.GNSS_EIRP_MODE      = GNSS_EIRP_MODE;      % gnssEIRPFromICD mode
    payload.GNSS_EIRP_MARGIN_dB = stored('%g', GNSS_EIRP_MARGIN_dB);   % used in "margin" mode
    payload.T_noise_K    = stored('%.6g', Tnoise7);
    payload.G_ant_dB     = stored('%.4f', G_ant7);     % from the generated patterns
    payload.FBcone_dB    = stored('%.3f', FB7);        % 0-60 over 120-180 cone
    payload.backFrac     = stored('%.5f', back7);
    payload.T_integ_s    = stored('%.8g', T_integ7);
    payload.N_incoh      = N_incoh7;
    payload.N_chan       = NCH7;                       % SoOp carriers, GNSS signals
    payload.maximin      = stored('%.6g', iBest.passWorst);   % worst pass fraction over the required ports
    payload.passBand     = stored('%.4g', iBest.passBand);    % per band, min over required ports
    payload.PASS_REQ_BAND = stored('%.4g', PASS_REQ_BAND);    % per band, on the required ports
    payload.marginWorst  = stored('%.6g', iBest.marginWorst); % min(passBand - PASS_REQ_BAND)
    payload.objective    = stored('%.6g', fBest);      % min(marginWorst,0) - COST_WEIGHT*mass/budget + tie-break
    payload.mass_kg      = stored('%.4g', iBest.cost.mass_kg);      % I/P antenna + channels
    payload.mass_chan_kg = stored('%.4g', iBest.cost.channels_kg);  % of which correlator channels
    payload.stow_U       = stored('%.4g', iBest.cost.stow_U);
    payload.MASS_BUDGET_kg = stored('%.4g', MASS_BUDGET_kg);
    payload.STOW_BUDGET_U  = stored('%.4g', STOW_BUDGET_U);
    payload.assumedRMSE  = stored('%.6g', RMSE_TARGET);
