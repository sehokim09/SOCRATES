function idx = localGridIndex(th, ph, resDeg)
% LOCALGRIDINDEX  Linear index into a [nPhi x nTheta] pattern grid for each
%   (theta, phi) pair, radians in, nearest neighbour, nadir frame.
    nTheta = round(180/resDeg) + 1;  nPhi = round(360/resDeg) + 1;
    thd = min(max(double(th(:))*180/pi, 0), 180);
    phd = mod(double(ph(:))*180/pi, 360);
    it  = min(max(round(thd/resDeg) + 1, 1), nTheta);
    ip  = min(max(round(phd/resDeg) + 1, 1), nPhi);
    idx = sub2ind([nPhi nTheta], ip, it);
end

function [Tsys, Tant, Trec, Tsky] = localSysTemp(f_Hz, backFrac, NF_dB, T408, expo, Tearth, Lfe)
% LOCALSYSTEMP  T_sys = (1-b)*T_earth + b*T_sky + T_rx, with b the zenith
%   hemisphere fraction read off the generated pattern. The front-end loss is
%   one physical loss with two effects: signal attenuation (applied to S_0)
%   and noise here, (L-1)*290 plus the LNA referred through it.
    Tsky = T408*(408/(f_Hz/1e6))^expo + 2.7;
    Tant = (1 - backFrac)*Tearth + backFrac*Tsky;
    Trec = (Lfe - 1)*290 + Lfe*290*(10^(NF_dB/10) - 1);
    Tsys = Tant + Trec;
end

function [f, detail, info] = localMaximin(x, nch, PRE, BAND, isGNSS, freq, lambda, ...
                                          EIRP_dB, BW, alt_Tx, KIND, K)
% LOCALMAXIMIN  Worst band-and-port pass fraction for design vector x.
%   x = [D_gp, h, T_dwell_VU, T_dwell_L, NF_VU, NF_L, L_misc, alt_Rx_km]
%   The I/P patterns are generated here for the trial (D_gp, h) with
%   SAIAntennaPattern and cached in K.CACHE across calls that leave
%   (D_gp, h, alt_Rx) unchanged.
    D_gp = x(1);  h = x(2);
    if K.EQUAL_RES, TdL = x(3) + K.DWELL_OFFSET; else, TdL = x(4); end
    if isfield(K, 'DWELL_EPOCH') && K.DWELL_EPOCH > 0   % the tied L dwell must be implementable too
        TdL = max(K.DWELL_EPOCH, floor(TdL/K.DWELL_EPOCH + 1e-9)*K.DWELL_EPOCH);
    end
    TdIP = x(3) + localOffIP(K);                      % equal-footprint I/P dwells
    if isfield(K, 'DWELL_EPOCH') && K.DWELL_EPOCH > 0
        TdIP = max(K.DWELL_EPOCH, floor(TdIP/K.DWELL_EPOCH + 1e-9)*K.DWELL_EPOCH);
    end
    Tdw = [TdIP TdL];                                 % per-band dwell
    NF = [x(5) x(5) x(5) x(6)];  Lmisc = 10^(x(7)/10);  altRx = x(8)*1e3;
    detail = struct();  info = struct();  f = Inf;
    sumAll = 0;  nAll = 0;      % for the tie-breaker, see the end
    passBand = inf(1, numel(BAND));   % min over the REQUIRED ports of each band

    key = [D_gp h x(8)];                              % altitude sets the Earth-limb sky fraction
    if ~isKey(K.CACHE, 'key') || any(abs(K.CACHE('key') - key) > 1e-12)
        pat = cell(1, numel(BAND));
        for ib = 1:numel(BAND)
            if isGNSS(ib)
                pat{ib} = K.PATCH_L;
            else
                pat{ib} = SAIAntennaPattern(KIND(ib), freq(ib)/1e6, D_gp, h, K.RES_DEG, struct('alt_km', x(8)));
            end
        end
        K.CACHE('pat') = pat;
        K.CACHE('key') = key;
    end
    cachePat = K.CACHE('pat');

    for ib = 1:numel(BAND)
        nm = BAND(ib);  P = PRE.(nm);  A = cachePat{ib};
        % HVC uses the linear back fraction: same element, and the two differ
        % by under 0.1% at every band
        if K.RX_POL == "LHCP", bfrac = A.backFrac_cp; else, bfrac = A.backFrac; end
        [Tsys, Tant, Trec, Tsky] = localSysTemp(freq(ib), bfrac, NF(ib), ...
                                                K.T408, K.EXPO, K.TEARTH, Lmisc);
        A.Tsys = Tsys;  A.Tant = Tant;  A.Trec = Trec;  A.Tsky = Tsky;
        info.(nm) = A;

        [sTR, sTS, sSR] = localAltScale(P.theta, alt_Tx(ib), P.altRef, altRx, K.R_E);
        RD = P.rangeTR .* sTR;
        RR = P.rangeTS .* sTS + P.rangeSR .* sSR;

        if isGNSS(ib)
            % signal-averaged S_0: with nch = number of signals, S_0*N_c is the
            % sum over signals of lambda^2*EIRP*T_I; bandwidth cancels
            lam_i = K.c ./ (K.GNSS_SIG(:,1)*1e6);
            S0 = mean((lam_i.^2/(4*pi)) .* 10.^(K.GNSS_SIG(:,2)/10)) ...
                 / (K.kB*BW(ib)*Tsys) / Lmisc / (4*pi);
            T_I = K.T_I_GNSS;  kap = NaN;
        else
            S0 = (lambda(ib)^2/(4*pi)) * 10^(EIRP_dB(ib)/10) ...
                 / (K.kB*BW(ib)*Tsys) / Lmisc / (4*pi);
            tau = (P.rangeTS.*sTS + P.rangeSR.*sSR - RD)/K.c;
            T_I = max(min(tau), 1e-5);  kap = -1;
        end
        Nc = T_I*BW(ib)*nch(ib);
        T_dwell = Tdw(ib);
        eb = sqrt(1 + (K.eta_avg*sqrt(T_dwell/T_I))^2) - 1;

        for port = K.PORTS
            % X, Y: one port pattern read at both arrival directions, the
            % direct path pays the mismatch. L: the reflected arm reads the L
            % pattern (co-polar, front), the direct arm the R pattern
            % (co-polar through the back), no mismatch.
            switch port
                case "X",  PWr = A.XX.^2 + A.XY.^2;  PWd = PWr;   gpk = A.G_realized_dBi;   pm = K.POLMIS;
                case "Y",  PWr = A.YX.^2 + A.YY.^2;  PWd = PWr;   gpk = A.G_realized_dBi;   pm = K.POLMIS;
                case "L",  PWr = A.L.^2;             PWd = A.R.^2; gpk = A.G_realized_cp_dBi; pm = 0;
            end
            GR = 10*log10(max(PWr(P.iR), 1e-30)) + gpk;
            if isGNSS(ib)
                thr = 1/(eb*S0*Nc*P.Ginv.(port));
                ok  = 10.^(GR/10)./RR.^2 > thr;
            else
                GD = 10*log10(max(PWd(P.iD), 1e-30)) + gpk - pm;
                SD = S0*10.^(GD/10)./RD.^2;                     % direct SNR per observation
                beta = 10.^((20*log10(RD./RR) + GR - GD)/10);
                [Pobs, ok1] = localWindowPass(SD, eb*Nc, kap, beta, P.cdfX.(port), P.cdfF.(port));
                ok = (Pobs > K.gammaReq) & ok1;                 % Tests 2 and 1, as evaluateReceiver
            end
            % equal group weight: the mean over geometry groups of the
            % within-group fraction
            passG = accumarray(P.grp, double(ok), [P.nGrp 1], @mean, NaN);
            pass  = mean(passG, 'omitnan');
            detail.(nm).(port) = pass;
            detail.(nm).byGroup.(port) = passG.';
            if any(K.reqPorts{ib} == port), f = min(f, pass);  passBand(ib) = min(passBand(ib), pass); end
            sumAll = sumAll + pass;  nAll = nAll + 1;
        end
    end
    % Lexicographic tie-break (1e-4 times the mean of all pass fractions keeps
    % the other bands optimized without outranking the worst one), then the
    % requirement-then-mass objective
    [massKg, stowU, costN, parts] = localAntennaCost(D_gp, h, nch, K);
    margin = passBand - K.PASS_REQ_BAND;             % per band, on the required ports
    [mWorst, ibW] = min(margin);
    info.passWorst   = f;                            % raw maximin over required ports
    info.passBand    = passBand;                     % per band, min over required ports
    info.margin      = margin;
    info.marginWorst = mWorst;                       % what the objective works on
    info.bandWorst   = BAND(ibW);                    % the band setting it
    info.passAtWorst = passBand(ibW);  info.reqAtWorst = K.PASS_REQ_BAND(ibW);
    info.cost = parts;
    info.cost.mass_kg = massKg;  info.cost.stow_U = stowU;  info.cost.costN = costN;
    f = min(mWorst, 0) - K.COST_WEIGHT*costN + 1e-4*(sumAll/max(nAll,1));
    if massKg > K.MASS_BUDGET_kg || stowU > K.STOW_BUDGET_U
        f = f - 1 - costN;                           % infeasible, monotone
    end
end

function [mass_kg, stow_U, costN, parts] = localAntennaCost(D_gp, h, nch, K)
% LOCALANTENNACOST  Mass and stowed volume of the I/P antenna and the channels.
%   Tensioned metallized-membrane reflector on four tape-spring perimeter
%   booms, deployed from the bus deck; the crossed dipoles deployed from a
%   module on the nadir face, on four struts only if h exceeds the module
%   thickness; one correlator channel per carrier or signal tracked. Only the
%   deployed excess over the bare face and the module costs anything beyond
%   the fixed element mass.
    Dx   = max(D_gp - K.D_DECK, 0);              % deployed excess, m
    Aref = max(D_gp^2 - K.D_DECK^2, 0);          % deployed reflector area, m^2
    parts = struct();
    parts.surface_kg  = K.RHO_AREAL * Aref;      % membrane, coating, edge tensioning
    parts.booms_kg    = K.RHO_BOOM  * 4*Dx;      % four perimeter booms with root hinges
    parts.standoff_kg = K.RHO_BOOM  * 4*max(h - K.H_DEPLOYER, 0);   % struts only above the deployer module
    parts.elements_kg = K.M_ELEM;                % dipoles, deployers, baluns (fixed)
    parts.channels_kg = K.M_CHAN * sum(nch);     % correlator channels
    parts.plane_kg    = K.GP_MASS;               % the ground-plane option's own mass (0 for a bus face)
    mass_kg = parts.surface_kg + parts.booms_kg + parts.standoff_kg + parts.elements_kg + parts.channels_kg + parts.plane_kg;
    stow_U  = K.STOW_ELEM_U + K.STOW_U_PER_M * Dx;
    costN   = mass_kg / K.MASS_BUDGET_kg;        % 1 = at the allocation
end

