        strtrim(sprintf('%.4f ', iBest.passBand)), strtrim(sprintf('%.4f ', i0.passBand)), ...
        strtrim(sprintf('%d ', bestN)), iBest.cost.mass_kg, iBest.cost.stow_U);
    info.baseline = struct('x', X0, 'nch', nch0, 'passBand', i0.passBand, ...
