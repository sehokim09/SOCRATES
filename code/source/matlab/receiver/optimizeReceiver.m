function [sTR, sTS, sSR] = localAltScale(theta, altT, altRef, altNew, R_E)
%   altRef may be a vector (per-observation simulation altitude).
    if all(abs(altNew - altRef) < 1)
        sTR = ones(size(theta));  sTS = sTR;  sSR = sTR;  return
    end
    [a1, b1, d1] = localSpecular(theta, altRef, altT, R_E);
    [a2, b2, d2] = localSpecular(theta, altNew, altT, R_E);
    sSR = a2./a1;  sTS = b2./b1;  sTR = d2./d1;
end

function T_I = localFlownTI(P, altT, altRx, R_E, c, step)
% LOCALFLOWNTI  Coherent integration time of a SoOp band flown at receiver
%   altitude altRx [m]: the shortest tau_RD of the whole cut sample, rounded
%   down to a multiple of step when step > 0 (as T_integ7).
    T_I = max(localTauMin(P.tau, altT, altRx, R_E, c, false), 1e-5);
    if step > 0, T_I = max(step, floor(T_I/step)*step); end
end

function tmin = localTauMin(Pt, altT, altRx, R_E, c, visOnly)
% LOCALTAUMIN  Shortest tau_RD [s] at receiver altitude altRx [m] over the
%   shortest-tau_RD observations of the whole cut sample (Pt = P.tau). With
%   visOnly, a transmitter below the receiver's local horizontal plane at a
%   scaled altitude is skipped, as localPassFraction does.
    [sTR, sTS, sSR] = localAltScale(Pt.theta, altT, Pt.altRef, altRx, R_E);
    RD  = Pt.rangeTR.*sTR;
    tau = (Pt.rangeTS.*sTS + Pt.rangeSR.*sSR - RD)/c;
    if visOnly && any(abs(altRx - Pt.altRef) >= 1)
        tau = tau((R_E + altT)^2 > (R_E + altRx).^2 + RD.^2);
    end
    tmin = min(tau);
end

function [RSR, RTS, RTR] = localSpecular(theta, altR, altT, R_E)
%   altR may be scalar or a vector the size of theta (elementwise throughout).
    ct = cos(theta);
    RSR = -R_E*ct + sqrt((R_E*ct).^2 + (R_E+altR).^2 - R_E^2);
    RTS = -R_E*ct + sqrt((R_E*ct).^2 + (R_E+altT).^2 - R_E^2);
    aR  = asin(min(1, max(-1, RSR.*sin(theta)./(R_E+altR))));
    aT  = asin(min(1, max(-1, RTS.*sin(theta)./(R_E+altT))));
    psi = aR + aT;
    RTR = sqrt((R_E+altR).^2 + (R_E+altT).^2 - 2*(R_E+altR).*(R_E+altT).*cos(psi));
end

function F = localCdf(Xu, Fu, xq)
    F = interp1(Xu, Fu, xq, 'linear', NaN);
    F(xq <= Xu(1)) = 0;  F(xq >= Xu(end)) = 1;
end

function [Pobs, valid] = localWindowPass(SD, ebNc, kap, beta, Xu, Fu)
% LOCALWINDOWPASS  Per-observation Test 2 with the direct-SNR-dependent
%   window, as evaluateReceiver evaluates it:
%       N_D = 1 + 1/S_D,   C = (eta_bar*N_c - kappa - 2*N_D)/2,
%       rho_e = C +/- sqrt(C^2 - N_D^2),   Gamma window = rho_e/beta,
%       P = F(Gamma_upper) - F(Gamma_lower).
%   The window exists iff C >= N_D, which is Test 1 (returned as valid).
    ND = 1 + 1./SD;
    C  = (ebNc - kap - 2*ND)/2;
    valid = C > ND;
    r  = sqrt(max(C.^2 - ND.^2, 0));
    Pobs = localCdf(Xu, Fu, (C + r)./beta) - localCdf(Xu, Fu, (C - r)./beta);
    Pobs(~valid) = 0;
end

function [xb, fb] = localCompassSearch(fun, x0, lb, ub)
    xb = min(max(x0, lb), ub);  fb = fun(xb);
    step = 0.25;
    while step > 2e-3
        improved = false;
        for iv = 1:numel(xb)
            for s = [1 -1]
                xt = xb;
                xt(iv) = min(max(xb(iv) + s*step*(ub(iv)-lb(iv)), lb(iv)), ub(iv));
                if xt(iv) == xb(iv), continue; end
                ft = fun(xt);
                if ft > fb + 1e-9, xb = xt; fb = ft; improved = true; end
            end
        end
        if ~improved, step = step/2; end
    end
end

function localPrintDetail(detail, BAND, vprintf)
    ports = string(fieldnames(detail.(BAND(1))))';
    ports = ports(~ismember(ports, ["byGroup" "joint"]));   % per-group breakdown is printed separately
    vprintf('\n  %-10s', 'band'); vprintf(' %10s', "port " + ports); vprintf(' %10s\n', 'joint');
    for ib = 1:numel(BAND)
        vprintf('  %-10s', BAND(ib));
        for p = ports, vprintf(' %10.3f', detail.(BAND(ib)).(p)); end
        vprintf(' %10.3f\n', detail.(BAND(ib)).joint);
    end
end

